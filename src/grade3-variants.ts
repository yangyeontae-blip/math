export interface Grade3Variant { kind: 'choice' | 'number'; prompt: string; answer: string; wrongs?: string[]; explanation: string; visual: CurriculumVisual; hints?: [string, string, string] }
type Item = readonly [prompt: string, answer: string, wrongs: readonly string[], explanation?: string];
type Rand = () => number;

const pick = <T>(items: readonly T[], r: Rand) => items[Math.min(items.length - 1, Math.floor(r() * items.length))];
const ri = (min: number, max: number, r: Rand) => min + Math.floor(r() * (max - min + 1));
const geo = (shape: Extract<CurriculumVisual, { kind: 'geometry' }>['shape'], label?: string): CurriculumVisual => ({ kind: 'geometry', shape, label });
const fromItems = (items: readonly Item[], visual: CurriculumVisual, kind: 'choice' | 'number' = 'choice') => (r: Rand): Grade3Variant => {
  const [prompt, answer, wrongs, explanation] = pick(items, r);
  return { kind, prompt, answer, wrongs: [...wrongs], explanation: explanation ?? `${j(answer, '이가')} 알맞아요.`, visual };
};

