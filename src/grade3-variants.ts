/** 이 임무에 변형이 있는지 알려 줘요(변형이 없는 임무는 난수를 쓰지 않아 기존 출제 흐름이 그대로예요). */
export function grade3HasVariant(unit: NewCurriculumUnitId, mission: number): boolean {
  return (unit === 'plane' && mission <= 7) || (unit === 'lengthTime' && mission === 2) || (unit === 'fractionDecimal' && [0, 4, 5, 6].includes(mission)) || (unit === 'measurement' && mission <= 2);
}

/** 3학년 문제 중 질문이 너무 빨리 되풀이되는 임무에 섞어 쓰는 변형이에요. */
export function grade3Variant(unit: NewCurriculumUnitId, mission: number, random: Rand): Grade3Variant | null {
  if (unit === 'plane' && mission <= 7) { const extra = planeExtra[mission] as ((r: Rand) => Grade3Variant) | undefined; return extra && random() < .4 ? extra(random) : planeBank[mission](random); }
  if (unit === 'lengthTime' && mission === 2) return lengthBank(random);
  if (unit === 'fractionDecimal') { if (mission === 0) return fractionMeaning(random); if (mission === 4) return decimalMeaning(random); if (mission === 5) return decimalReading(random); if (mission === 6) return fractionDecimalPair(random); }
  if (unit === 'measurement') { if (mission === 0) return capacityBank(random); if (mission === 1) return weightBank(random); if (mission === 2) return estimateBank(random); }
  return null;
}
